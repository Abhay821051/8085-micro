; 2nd 8bit in loc 2052h
; sum in 2053h

; LOAD B REG W/T NUM 1
MVI B,7
; LOAD C REG W/T NUM 2
MVI C,3

; LOAD HL 2051 FOR B DATA
LXI H,2051H
; LOAD MEM 2051 W/T B DATA
MOV M,B

; LOAD HL 2052 FOR C DATA
LXI H,2052H
; LOAD MEM 2052 W/T C DATA
MOV M,C

; LOAD HL 2051 FOR B DATA TO ACU
LXI H,2051H
; LOAD MEM 2051 DATA TO ACU
MOV A,M

; LOAD HL 2052 FOR C DATA TO ACU
LXI H,2052H
; ADD MEM 2052 DATA TO ACU
ADD M

; LOAD 2053 TO HL
LXI H,2053H
; MOV ACU DATA TO MEM 2053
MOV M,A

